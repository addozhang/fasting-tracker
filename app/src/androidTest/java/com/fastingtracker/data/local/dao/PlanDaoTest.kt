package com.fastingtracker.data.local.dao

import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.fastingtracker.data.local.AppDatabase
import com.fastingtracker.data.local.entity.PlanEntity
import com.fastingtracker.domain.model.PlanType
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Assert.*
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.time.Instant

@RunWith(AndroidJUnit4::class)
class PlanDaoTest {

    private lateinit var db: AppDatabase
    private lateinit var planDao: PlanDao

    private val now = Instant.now()

    @Before
    fun setup() {
        db = Room.inMemoryDatabaseBuilder(
            ApplicationProvider.getApplicationContext(),
            AppDatabase::class.java
        ).allowMainThreadQueries().build()
        planDao = db.planDao()
    }

    @After
    fun tearDown() {
        db.close()
    }

    private fun makePlan(
        id: Long? = null,
        name: String = "Test Plan",
        fastingHours: Int = 16,
        eatingHours: Int? = 8,
        isDefault: Boolean = false
    ) = PlanEntity(
        id = id,
        name = name,
        planType = PlanType.DAILY,
        fastingHours = fastingHours,
        eatingHours = eatingHours,
        isDefault = isDefault,
        createdAt = now,
        updatedAt = now
    )

    @Test
    fun insertAndGetById() = runTest {
        val id = planDao.insert(makePlan(name = "16:8"))
        val plan = planDao.getById(id)

        assertNotNull(plan)
        assertEquals("16:8", plan!!.name)
        assertEquals(16, plan.fastingHours)
        assertEquals(8, plan.eatingHours)
    }

    @Test
    fun insertReturnsAutoGeneratedId() = runTest {
        val id1 = planDao.insert(makePlan(name = "Plan A"))
        val id2 = planDao.insert(makePlan(name = "Plan B"))

        assertTrue(id1 > 0)
        assertTrue(id2 > id1)
    }

    @Test
    fun observeAllReturnsInsertedPlans() = runTest {
        planDao.insert(makePlan(name = "16:8"))
        planDao.insert(makePlan(name = "18:6"))

        val plans = planDao.observeAll().first()
        assertEquals(2, plans.size)
    }

    @Test
    fun updatePlan() = runTest {
        val id = planDao.insert(makePlan(name = "Old Name"))
        val plan = planDao.getById(id)!!

        planDao.update(plan.copy(name = "New Name"))
        val updated = planDao.getById(id)

        assertEquals("New Name", updated!!.name)
    }

    @Test
    fun deletePlan() = runTest {
        val id = planDao.insert(makePlan(name = "To Delete"))
        assertNotNull(planDao.getById(id))

        planDao.delete(planDao.getById(id)!!)
        assertNull(planDao.getById(id))
    }

    @Test
    fun getByIdReturnsNullForNonExistent() = runTest {
        val plan = planDao.getById(999L)
        assertNull(plan)
    }

    @Test
    fun isDefaultFieldPersisted() = runTest {
        val defaultId = planDao.insert(makePlan(name = "16:8", isDefault = true))
        val customId = planDao.insert(makePlan(name = "Custom", isDefault = false))

        assertTrue(planDao.getById(defaultId)!!.isDefault)
        assertFalse(planDao.getById(customId)!!.isDefault)
    }

    @Test
    fun insertAllPersistsMultiplePlans() = runTest {
        val plans = listOf(
            makePlan(id = 1L, name = "16:8", isDefault = true),
            makePlan(id = 2L, name = "18:6", isDefault = true),
            makePlan(id = 3L, name = "20:4", isDefault = true)
        )
        planDao.insertAll(plans)

        val all = planDao.observeAll().first()
        assertEquals(3, all.size)
        assertTrue(all.all { it.isDefault })
    }

    @Test
    fun insertWithFixedIdPreservesId() = runTest {
        planDao.insert(makePlan(id = 42L, name = "Fixed ID Plan"))
        val plan = planDao.getById(42L)

        assertNotNull(plan)
        assertEquals("Fixed ID Plan", plan!!.name)
    }
}
